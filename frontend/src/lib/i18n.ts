export type StringKey = keyof typeof STRINGS.zh;

// 校验 zh/en key 一一对齐(无孤儿)——构建/测试时调用,缺失即抛。
export function assertKeysAligned(): void {
  const zhKeys = Object.keys(STRINGS.zh).sort();
  const enKeys = Object.keys(STRINGS.en).sort();
  const onlyZh = zhKeys.filter((k) => !(k in STRINGS.en));
  const onlyEn = enKeys.filter((k) => !(k in STRINGS.zh));
  if (onlyZh.length || onlyEn.length) {
    throw new Error(`i18n key 不对齐 — 仅 zh: [${onlyZh}] 仅 en: [${onlyEn}]`);
  }
}

let _lang: Lang = 'zh';
const listeners = new Set<() => void>();

export function initLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'zh' || saved === 'en') _lang = saved;
  } catch {
    /* ignore */
  }
  return _lang;
}
export function getLang(): Lang {
  return _lang;
}
export function setLang(lang: Lang): void {
  if (lang !== 'zh' && lang !== 'en') return;
  _lang = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  listeners.forEach((fn) => fn());
}
export function onLangChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}
export function t(key: StringKey): string {
  const dict = STRINGS[_lang] as Record<string, string>;
  if (dict[key] !== undefined) return dict[key];
  const zh = STRINGS.zh as Record<string, string>;
  return zh[key] !== undefined ? zh[key] : key;
}
